import { existsSync } from 'node:fs';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const contract = new URL('../contracts/openapi.json', import.meta.url);
const output = new URL('../src/lib/api/generated.ts', import.meta.url);
const mode = process.argv[2];
if (!['generate', 'check'].includes(mode))
  throw new Error('Usar generate o check.');
if (!existsSync(contract)) {
  const message =
    'PENDIENTE: falta contracts/openapi.json aprobado y exportado por FastAPI. No se generan DTO ficticios.';
  if (mode === 'generate' || existsSync(output)) {
    console.error(message);
    process.exitCode = 1;
  } else
    console.log(
      `${message} El control de consistencia se activará automáticamente al incorporarlo.`,
    );
} else {
  const generated =
    '// Generated by npm run api:generate. Do not edit.\n' +
    astToString(await openapiTS(contract));
  if (mode === 'generate') {
    await writeFile(output, generated, 'utf8');
    console.log(`Generado ${fileURLToPath(output)}`);
  } else if (
    !existsSync(output) ||
    (await readFile(output, 'utf8')).replaceAll('\r\n', '\n') !== generated
  ) {
    console.error(
      'DTO desactualizados: ejecutar npm run api:generate y versionar ambos archivos.',
    );
    process.exitCode = 1;
  } else console.log('OpenAPI y tipos generados: consistentes.');
}
